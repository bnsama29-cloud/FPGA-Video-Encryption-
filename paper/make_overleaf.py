"""Self-contained Overleaf projects of both papers: paper/overleaf/{conference,access}/ and a .zip of each.

    python paper/make_overleaf.py

Follows \\documentclass, \\input, \\includegraphics, \\bibliography and the ieeeaccess class's images from each main
file and copies exactly the files it needs, with the same folder structure, so the project compiles on Overleaf
as it is (upload the zip: New Project -> Upload Project; the main file is conference.tex / access.tex).
Generated: never edit the copies, edit the paper/ sources (and run paper/make_assets.py) and rerun this script.
"""
import re
import shutil
import sys
import zipfile
from pathlib import Path

PAPER = Path(__file__).resolve().parent
OUT = PAPER / "overleaf"
GRAPHICS_EXT = ["", ".pdf", ".png", ".jpg"]
RE_INPUT = re.compile(r"\\(?:input|include)\{([^}]+)\}")
RE_GRAPHICS = re.compile(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}")
RE_BIB = re.compile(r"\\bibliography\{([^}]+)\}")
RE_CLASS = re.compile(r"\\documentclass(?:\[[^\]]*\])?\{([^}]+)\}")


def strip_comments(text):
    return re.sub(r"(?<!\\)%.*", "", text)


def find(name, exts, search=("",)):
    for d in search:
        for e in exts:
            p = PAPER / d / (name + e if not name.endswith(e) or not e else name)
            if p.is_file():
                return p
    return None


def collect(main):
    """Every file the main .tex needs, relative to paper/."""
    need, todo, missing = set(), [PAPER / main], []
    gpath = ("access/", "") if main.startswith("access") else ("",)
    while todo:
        f = todo.pop()
        if f in need:
            continue
        need.add(f)
        text = strip_comments(f.read_text(encoding="utf-8"))
        for m in RE_INPUT.findall(text):
            p = find(m, ["", ".tex"])
            (todo.append(p) if p else missing.append(f"{m} (from {f.name})"))
        for m in RE_GRAPHICS.findall(text):
            p = find(m, GRAPHICS_EXT, gpath)
            (need.add(p) if p else missing.append(f"{m} (from {f.name})"))
        for m in RE_BIB.findall(text):
            for b in m.split(","):
                p = find(b.strip(), [".bib"])
                (need.add(p) if p else missing.append(f"{b}.bib"))
        for m in RE_CLASS.findall(text):
            p = find(m, [".cls"])
            if p:                                    # IEEEtran is on Overleaf; ieeeaccess.cls is ours
                need.add(p)
                if m == "ieeeaccess":                # the class draws its logos from access/*.png
                    need.update((PAPER / "access").glob("*.png"))
    return need, missing


def build(main):
    name = Path(main).stem
    dest = OUT / name
    shutil.rmtree(dest, ignore_errors=True)
    need, missing = collect(main)
    for f in sorted(need):
        rel = f.relative_to(PAPER)
        (dest / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(f, dest / rel)
    (dest / "README.txt").write_text(
        f"Overleaf project for {main}, generated by paper/make_overleaf.py -- do not edit these copies.\n"
        f"Upload {name}.zip on Overleaf (New Project -> Upload Project); main file: {main}; compiler: pdfLaTeX.\n",
        encoding="utf-8")
    zp = OUT / f"{name}.zip"
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(dest.rglob("*")):
            if f.is_file():
                z.write(f, f.relative_to(dest))
    print(f"{name}: {len(need)} files -> {dest.relative_to(PAPER.parent)} and {zp.name}")
    return missing


def main():
    missing = build("conference.tex") + build("access.tex")
    if missing:
        print("MISSING (the project will not compile):\n  " + "\n  ".join(missing))
        sys.exit(1)


if __name__ == "__main__":
    main()
