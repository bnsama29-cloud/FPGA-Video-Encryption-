INK, INK2, GRID, SURFACE = "#0b0b0b", "#52514e", "#e1e0d9", "#ffffff"
macros = {}


def J(path):
    return json.loads(Path(path).read_text())


def ms(v, nd=2):
    v = [x for x in v if isinstance(x, (int, float))]
    if not v:
        return r"\TODO{n/a}"
    sd = st.stdev(v) if len(v) > 1 else 0.0
    return f"{st.mean(v):.{nd}f}\\,$\\pm$\\,{sd:.{nd}f}"


def macro(name, value):
    macros[name] = value


def write(name, body):
    """Every table is scaled to the column width, so wide ones never overflow into the next column."""
    body = re.sub(r"(\\begin\{tabular\}\{[^}]*\})", r"\\resizebox{\\columnwidth}{!}{%\n\1", body, count=1)
    body = body.replace("\\end{tabular}", "\\end{tabular}}", 1)
    (TAB / name).write_text("% generated by paper/make_assets.py from paper/data -- do not edit\n" + body)


def vga_cpp():
    """Cycles per pixel of a 640x480 frame, measured in RTL simulation (research R1), or None."""
    sc = RES / "stall_profile" / "scaling.json"
    if not sc.exists():
        return None
    return next((p["cpp"] for p in J(sc)["points"] if p["size"] == "640x480"), None)


def size_channel():
    """R7: the frame-size side channel of every level and the cost of constant-size frames
    (paper/data/research/size_leak). E0-E5 and padding rows only; the FF+PI row waits for a rerun."""
    d = RES / "size_leak"
    if not d.exists():
        return
    res = {f.stem: J(f)["results"] for f in sorted(d.glob("*.json")) if f.stem in ALL_LABEL}   # labelled only
    lv = ["E0", "E1", "E2", "E3", "E4", "E5"]
    sep = {k: [v[l]["event_auc"] for l in lv] for k, v in res.items()}
    films = [k for k in res if k != "synthetic"]
    macro("LeakFixedMin", f"{min(sep['synthetic']):.2f}")
    macro("LeakFixedMax", f"{max(sep['synthetic']):.2f}")
    macro("LeakFilmMin", f"{min(min(sep[k]) for k in films):.2f}")
    macro("LeakFilmMax", f"{max(max(sep[k]) for k in films):.2f}")
    macro("LeakLevelSpread", f"{max(max(v) - min(v) for v in sep.values()):.2f}")
    macro("NumFilms", NUMWORD.get(len(films), str(len(films))))
    pad = {k: 100 * (v["E2 pad-max"]["bytes_vs_E2"] - 1) for k, v in res.items()}
    macro("PadFixed", f"{pad['synthetic']:.0f}")
    macro("PadFilmMin", f"{min(pad[k] for k in films):.0f}")
    macro("PadFilmMax", f"{max(pad[k] for k in films):.0f}")


def _style():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size": 8, "font.family": "serif", "axes.edgecolor": INK2, "axes.labelcolor": INK,
                         "xtick.color": INK2, "ytick.color": INK2})
    return plt


def _clean(ax, grid="y"):
    if grid:
        ax.grid(axis=grid, color=GRID, lw=0.6)
    ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)


