def J(path):
    return json.loads(Path(path).read_text())


def ms(v, nd=2):
    v = [x for x in v if isinstance(x, (int, float))]
    if not v:
        return r"\TODO{n/a}"
    sd = st.stdev(v) if len(v) > 1 else 0.0
    return f"{st.mean(v):.{nd}f}\\,$\\pm$\\,{sd:.{nd}f}"


def macro(name, value):
    macros[name] = value


def write(name, body):
    """Every table is scaled to the column width, so wide ones never overflow into the next column."""
    body = re.sub(r"(\\begin\{tabular\}\{[^}]*\})", r"\\resizebox{\\columnwidth}{!}{%\n\1", body, count=1)
    body = body.replace("\\end{tabular}", "\\end{tabular}}", 1)
    (TAB / name).write_text("% generated by paper/make_assets.py from paper/data -- do not edit\n" + body)


