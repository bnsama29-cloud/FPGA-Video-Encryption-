def sign_recovery():
    """B35: Lin et al.'s sign-bit recovery LP against E1-E4 (experiments/sign_recovery.py), pooled over every
    source file in paper/data/references/sign_recovery/ (frames weighted equally)."""
    d = REFS / "sign_recovery"
    files = sorted(d.glob("*.json")) if d.exists() else []
    if not files:
        return
    rows, srcs = [], []
    for f in files:
        j = J(f)
        rows += [dict(r, src=f.stem) for r in j["rows"]]
        srcs.append(f.stem)
    # a blank frame (no AC coefficient, e.g. a fade to black) has no sign to recover: leave it out
    blank = {(r["src"], r["frame"]) for r in rows if r["mode"] == "LinU3" and r.get("sign_acc") != r.get("sign_acc")}
    rows = [r for r in rows if (r["src"], r["frame"]) not in blank]
