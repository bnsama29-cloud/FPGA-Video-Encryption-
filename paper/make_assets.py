def compare(r, cores):
    """Table: this work (from vivado_results.json + the RTL cycle benchmark) next to published designs
    (paper/data/related/compare.json, numbers copied from the cited sources, each checked)."""
    rel = DATA / "related" / "compare.json"
    if not rel.exists():
        return
    b = J(SIM / "benchmark_rtl" / "benchmark.json")["rtl"]
    u, mhz = r["util"], 1000 / r["period"]
    mpix = mhz / (vga_cpp() or st.mean(b["cycles_per_pixel"][m] for m in MODES[:5]))
    macro("TopMpix", f"{mpix:.0f}")
    f = lambda v, nd=0: "--" if v is None else (f"{v:,.{nd}f}".replace(",", "{,}"))
    rows = [f"Ours: encoder & Zynq-7020 & {f(u['lut'][0])} & {f(u['bram'][0], 1)} & {f(u['dsp'][0])} & "
            f"{mhz:.0f} & {mpix:.0f} & sel.\\ AEAD \\\\"]
    if cores:
        rows.append(f"Ours: one Ascon & Zynq-7020 & {min(c[3] for c in cores)}--{max(c[3] for c in cores)} & "
                    f"0 & 0 & {mhz:.0f} & -- & AEAD core \\\\")
    for x in J(rel)["rows"]:
        rows.append(f"{x['work']}~\\cite{{{x['cite']}}} & {x['device']} & {f(x['lut'])} & {f(x['bram'])} & "
                    f"{f(x['dsp'])} & {x['mhz']} & {f(x['mpix_s'])} & {x['crypto']} \\\\")
    write("tab_compare.tex", rf"""\begin{{table}}[t]
\caption{{Comparison with published FPGA designs. Their numbers are as reported by each source; ours are
post-route (Table~\ref{{tab:resources}}) with throughput from the RTL cycle count of a 640$\times$480 frame. Mpx/s: million pixels per second.}}
\label{{tab:compare}}
\centering\small
\begin{{tabular}}{{llrrrrrl}}
\toprule
Design & Device & LUT & BRAM & DSP & MHz & Mpx/s & Crypto \\
\midrule
{chr(10).join(rows)}
\bottomrule
\end{{tabular}}
\end{{table}}
""")


