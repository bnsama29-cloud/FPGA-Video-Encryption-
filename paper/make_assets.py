"""Build every table, number and figure of the paper from paper/data/ (never type a result by hand).

    python paper/make_assets.py            # or: cd paper && make tables

Reads   paper/data/ (the Kaggle results snapshot, plus yosys/ and, when they exist, vivado/ and board/)
Writes  paper/tables/numbers.tex   \\newcommand macros used in the prose (e.g. \\TtmMean)
        paper/tables/tab_*.tex     the tables, \\input by main.tex
        paper/figures/fig_*.pdf    the plots, and the visual-security grid copied from the data
A missing input becomes a red \\TODO{} in the PDF instead of a made-up number.
"""
import json
import re
import shutil
import statistics as st
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = HERE / "data"
SIM = DATA / "simulation"
TAB = HERE / "tables"
FIG = HERE / "figures"
MODES = ["E0", "E1", "E2", "E3", "E4", "E5"]
CLIP_LABEL = {"avengers": "Trailer A", "jailer": "Trailer B", "denzel": "Talk A", "challenge": "Talk B"}  # display order
BLUE, ORANGE = "#2a78d6", "#eb6834"            # validated categorical slots 1-2 (CVD ΔE 24.7)
INK, INK2, GRID, SURFACE = "#0b0b0b", "#52514e", "#e1e0d9", "#ffffff"
macros = {}


def J(path):
    return json.loads(Path(path).read_text())


def ms(v, nd=2):
    v = [x for x in v if isinstance(x, (int, float))]
    if not v:
        return r"\TODO{n/a}"
    sd = st.stdev(v) if len(v) > 1 else 0.0
    return f"{st.mean(v):.{nd}f}\\,$\\pm$\\,{sd:.{nd}f}"


def macro(name, value):
    macros[name] = value


def write(name, body):
    """Every table is scaled to the column width, so wide ones never overflow into the next column."""
    body = re.sub(r"(\\begin\{tabular\}\{[^}]*\})", r"\\resizebox{\\columnwidth}{!}{%\n\1", body, count=1)
    body = body.replace("\\end{tabular}", "\\end{tabular}}", 1)
    (TAB / name).write_text("% generated by paper/make_assets.py from paper/data -- do not edit\n" + body)


# ---------------------------------------------------------------- hardware
def hardware():
    b = J(SIM / "benchmark_rtl" / "benchmark.json")["rtl"]
    rows = "\n".join(f"{m} & {b['cycles'][m]} & {b['cycles_per_pixel'][m]:.3f} & "
                     f"{b['cycles'][m] - b['cycles']['E0']:+d} & {b['fps_640x480'][m]:.0f} \\\\"
                     for m in MODES[:5])
    write("tab_cycles.tex", rf"""\begin{{table}}[t]
\caption{{Encoder cycles per frame in RTL simulation ({b['size']}, {b['clock_mhz']:.0f}\,MHz). The last column extrapolates to 640$\times$480 at the same cycles per pixel.}}
\label{{tab:cycles}}
\centering\small
\begin{{tabular}}{{lrrrr}}
\toprule
Mode & Cycles & Cycles/pixel & $\Delta$ vs E0 & fps (640$\times$480) \\
\midrule
{rows}
\bottomrule
\end{{tabular}}
\end{{table}}
""")
    cpp = [b["cycles_per_pixel"][m] for m in MODES[:5]]
    macro("CyclesPerPixel", f"{st.mean(cpp):.2f}")
    macro("MaxExtraCycles", str(max(abs(b['cycles'][m] - b['cycles']['E0']) for m in MODES[:5])))
    macro("FpsVGA", f"{st.mean(b['fps_640x480'][m] for m in MODES[:5]):.0f}")
    macro("FpsHD", f"{1e8 / (st.mean(cpp) * 1280 * 720):.0f}")

    viv = DATA / "vivado" / "vivado_results.json"
    if viv.exists():                                      # Vivado post-route: the real numbers
        r = next(x for x in J(viv) if "secure_jpeg_top" in x["name"])
        u = r["util"]
        g = lambda k: f"{u[k][0]:g} ({u[k][2]:.1f}\\%)" if k in u else r"\TODO{?}"
        src = f"Vivado post-route, WNS {r['timing'].get('wns', 0):.3f}\\,ns at {1000 / r['period']:.0f}\\,MHz"
        body = f"Encoder (all) & {g('lut')} & {g('ff')} & {g('bram')} & {g('dsp')} \\\\"
        macro("ResourceSource", "Vivado post-route")
    else:                                                 # until then: Yosys estimate, clearly labelled
        def yosys(name):
            p = DATA / "yosys" / name
            if not p.exists():
                return None
            t = p.read_text()
            c = lambda pat: sum(int(n) for n in re.findall(rf"^\s+(\d+)\s+{pat}\b", t, re.M))
            luts = c("LUT[1-6]") + 4 * c("RAM64M") + 2 * c("RAM32M")
            return dict(lut=luts, ff=c("FD[RSCP]E"), bram=c("RAMB36E1") + c("RAMB18E1") / 2, dsp=c("DSP48E1"))
        top, ks, tg, se = (yosys(f) for f in ("yosys_secure_jpeg_top.txt", "yosys_keystream_gen.txt",
                                              "yosys_tag_unit.txt", "yosys_selective_enc.txt"))
        dev = dict(lut=53200, ff=106400, bram=140, dsp=220)
        fmt = lambda d, k: (f"{d[k]:g} ({100 * d[k] / dev[k]:.1f}\\%)" if d else r"\TODO{?}")
        body = f"Encoder (all) & {fmt(top, 'lut')} & {fmt(top, 'ff')} & {fmt(top, 'bram')} & {fmt(top, 'dsp')} \\\\\n"
        for label, d in (("\\quad keystream generator", ks), ("\\quad tag unit", tg), ("\\quad selective-encryption stage", se)):
            if d:
                body += f"{label} & {d['lut']} & {d['ff']} & {d['bram']:g} & {d['dsp']} \\\\\n"
        src = r"Yosys \texttt{synth\_xilinx} estimate, \textbf{not} post-route; \TODO{replace with Vivado (GUIDE.md 4.1)}"
        macro("ResourceSource", "a Yosys synthesis estimate")
        if top and ks and tg:
            macro("CryptoLutShare", f"{100 * (ks['lut'] + tg['lut']) / top['lut']:.0f}")
            macro("TopLuts", f"{top['lut']:,}".replace(",", "{,}"))
            macro("TopLutPct", f"{100 * top['lut'] / dev['lut']:.1f}")
    write("tab_resources.tex", rf"""\begin{{table}}[t]
\caption{{Resources on the xc7z020 (53\,200 LUT, 106\,400 FF, 140 BRAM36, 220 DSP). Source: {src}.}}
\label{{tab:resources}}
\centering\small
\begin{{tabular}}{{lrrrr}}
\toprule
Block & LUT & FF & BRAM36 & DSP \\
\midrule
{body.strip()}
\bottomrule
\end{{tabular}}
\end{{table}}
""")


# ---------------------------------------------------------------- leakage, jigsaw, learned
def leakage():
    srcs = {"Synthetic": SIM / "mode_tradeoff.json"}
    for clip, label in CLIP_LABEL.items():                  # fixed column order: Trailer A, B, Talk A, B
        if (SIM / "real" / clip / "mode_tradeoff.json").exists():
            srcs[label] = SIM / "real" / clip / "mode_tradeoff.json"
    data = {k: J(v)["modes"] for k, v in srcs.items()}
    names = list(data)
    real = [n for n in names if n != "Synthetic"]
    rows = []
    for m in MODES:
        cells = " & ".join(f"{data[n][m]['edge_corr']:.2f}" for n in names)
        rows.append(f"{m} & {data['Synthetic'][m]['cost']:.3f} & {cells} \\\\")
    write("tab_leakage.tex", rf"""\begin{{table}}[t]
\caption{{Outline leakage: edge correlation between the original and the eavesdropper's best keyless reconstruction (decode or replacement attack), 20 frames per source (0 = no outline). ``Enc.'' is the fraction of payload bits encrypted.}}
\label{{tab:leakage}}
\centering\small\setlength{{\tabcolsep}}{{3.5pt}}
\begin{{tabular}}{{ll{'r' * len(names)}}}
\toprule
Mode & Enc. & {' & '.join(names)} \\
\midrule
{chr(10).join(rows)}
\bottomrule
\end{{tabular}}
\end{{table}}
""")
    e14 = [data[n][m]["edge_corr"] for n in real for m in ("E1", "E2", "E3", "E4")]
    e5 = [data[n]["E5"]["edge_corr"] for n in real]
    macro("NumClips", str(len(real)))
    macro("LeakEOneFourMin", f"{min(e14):.2f}")
    macro("LeakEOneFourMax", f"{max(e14):.2f}")
    macro("LeakEFiveMin", f"{min(e5):.3f}")
    macro("LeakEFiveMax", f"{max(e5):.3f}")
    macro("CostEtwo", f"{100 * data['Synthetic']['E2']['cost']:.1f}")
    macro("CostEfour", f"{100 * data['Synthetic']['E4']['cost']:.1f}")
    macro("CostEfive", f"{100 * data['Synthetic']['E5']['cost']:.1f}")

    # figure: leakage vs encrypted share, one point per mode, range over the sources
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size": 8, "font.family": "serif", "axes.edgecolor": INK2, "axes.labelcolor": INK,
                         "xtick.color": INK2, "ytick.color": INK2})
    fig, ax = plt.subplots(figsize=(3.4, 2.2))
    for m in MODES:
        x = 100 * data["Synthetic"][m]["cost"]
        ys = [data[n][m]["edge_corr"] for n in names]
        ax.plot([x, x], [min(ys), max(ys)], color=BLUE, lw=2, solid_capstyle="round", zorder=2)
        ax.plot(x, st.mean(ys), "o", ms=6, color=BLUE, mec="white", mew=1.5, zorder=3)
        dx, ha = {"E1": (-4, "right"), "E2": (4, "left"), "E3": (-4, "right"), "E4": (4, "left"),
                  "E5": (5, "left")}.get(m, (0, "center"))
        ax.annotate(m, (x, max(ys)), xytext=(dx, 3), textcoords="offset points", ha=ha, color=INK, fontsize=7)
    ax.set_xlabel("payload bits encrypted (%)")
    ax.set_ylabel("edge correlation")
    ax.set_ylim(-0.08, 1.12)
    ax.grid(axis="y", color=GRID, lw=0.6)
    ax.set_axisbelow(True)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    fig.tight_layout()
    fig.savefig(FIG / "fig_leakage.pdf")
    plt.close(fig)

    jig = {"Synthetic": DATA / "future_work_results" / "jigsaw.json"}
    for clip, label in CLIP_LABEL.items():
        if (SIM / "real" / clip / "jigsaw" / "jigsaw.json").exists():
            jig[label] = SIM / "real" / clip / "jigsaw" / "jigsaw.json"
    jr = []
    for n, p in jig.items():
        s = J(p)["summary"]
        f = lambda k: f"{s[k]['mean']:.3f}"
        jr.append(f"{n} & {100 * s['neighbour_accuracy']['mean']:.1f} & {f('edge_corr_solved')} & {f('edge_corr_perfect_placement')} \\\\")
        if n != "Synthetic":
            macros.setdefault("_nb", []).append(100 * s["neighbour_accuracy"]["mean"])
            macros.setdefault("_oracle", []).append(s["edge_corr_perfect_placement"]["mean"])
    write("tab_jigsaw.tex", rf"""\begin{{table}}[t]
\caption{{E5 against a greedy jigsaw solver (8 frames per source). ``Oracle'' places every block correctly, which is the outline E5 hides.}}
\label{{tab:jigsaw}}
\centering\small
\begin{{tabular}}{{lrrr}}
\toprule
Source & Correct neighbours (\%) & Edge corr. solved & Edge corr. oracle \\
\midrule
{chr(10).join(jr)}
\bottomrule
\end{{tabular}}
\end{{table}}
""")
    macro("JigsawNeighboursMax", f"{max(macros.pop('_nb')):.1f}")
    o = macros.pop("_oracle")
    macro("JigsawOracleMin", f"{min(o):.2f}")
    macro("JigsawOracleMax", f"{max(o):.2f}")

    lr = []
    pairs = sorted((SIM / "real").glob("learned_pair*/results.json"))
    for i, p in enumerate(pairs, 1):
        for m, r in J(p).items():
            a, b = r["replacement_attack"], r["learned_attack"]
            lr.append(f"P{i} & {m} & {a['psnr']:.1f} / {a['ssim']:.2f} / {a['edge_corr']:.2f} & "
                      f"{b['psnr']:.1f} / {b['ssim']:.2f} / {b['edge_corr']:.2f} \\\\")
            if m == "E5":
                macros.setdefault("_e5edge", []).append(b["edge_corr"])
            if m in ("E2", "E4"):
                macros.setdefault("_ssim", []).append(b["ssim"])
    if pairs:
        r0 = J(pairs[0])["E2"]
        macro("LearnTrain", str(r0["train_frames"]))
        macro("LearnTest", str(r0["test_frames"]))
        macro("LearnEpochs", str(r0["epochs"]))
        macro("LearnEfiveEdgeMax", f"{max(abs(x) for x in macros.pop('_e5edge')):.3f}")
        macro("LearnSsimMax", f"{max(macros.pop('_ssim')):.2f}")
    write("tab_learned.tex", rf"""\begin{{table}}[t]
\caption{{Keyless reconstruction by a U-Net trained on one clip and tested on another (P1: Trailer A$\rightarrow$B, P2: Talk A$\rightarrow$B). Entries: PSNR (dB) / SSIM / edge correlation.}}
\label{{tab:learned}}
\centering\small\setlength{{\tabcolsep}}{{4pt}}
\begin{{tabular}}{{llcc}}
\toprule
Pair & Mode & Replacement attack & Learned attack \\
\midrule
{chr(10).join(lr) if lr else r"\multicolumn{4}{c}{\TODO{learned attack results missing}} \\"}
\bottomrule
\end{{tabular}}
\end{{table}}
""")


# ---------------------------------------------------------------- protocol + defence
def protocol():
    suite = sorted(SIM.glob("runs/full_suite_*_rep*/summary.json"))
    eps = {}
    for p in suite:
        for e in J(p)["episodes"]:
            eps.setdefault(e["type"], []).append(e)
    names = {"bitflip": "bit flips in the scan", "downgrade": "mode downgrade in header", "splice": "splice of two frames",
             "inject": "forged frame injection", "replay": "frame replay", "delay": "frame delay",
             "drop": "frame dropping", "flood": "junk flood", "fb_drop": "feedback dropping",
             "fb_forge": "forged feedback", "fb_replay": "feedback replay"}
    rows = []
    for t, es in eps.items():
        rej = [e["rx_first_rejection_s"] for e in es]
        rows.append(f"{names.get(t, t)} & {sum(e['time_to_mitigate_s'] is not None for e in es)}/{len(es)} & "
                    f"{ms(rej) if any(x is not None for x in rej) else '--'} & {ms([e['time_to_mitigate_s'] for e in es])} \\\\")
    S = [J(p) for p in suite]
    B = [J(p) for p in sorted(SIM.glob("runs/benign_*_rep*/summary.json"))]
    write("tab_attacks.tex", rf"""\begin{{table}}[t]
\caption{{Reaction to each active attack (full suite, threshold policy, {len(S)} runs; mean\,$\pm$\,s.d. in seconds). ``First rejection'' is when the receiver first discards a frame; ``mitigated'' is when the sender has raised protection or rekeyed.}}
\label{{tab:attacks}}
\centering\small\setlength{{\tabcolsep}}{{4pt}}
\begin{{tabular}}{{lccc}}
\toprule
Attack & Mitigated & First rejection & Mitigated after \\
\midrule
{chr(10).join(rows)}
\bottomrule
\end{{tabular}}
\end{{table}}
""")
    macro("SuiteRuns", str(len(S)))
    macro("NumAttacks", str(len(eps)))
    macro("TtmMean", f"{st.mean(x['mean_time_to_mitigate_s'] for x in S):.2f}")
    macro("TtmSd", f"{st.stdev([x['mean_time_to_mitigate_s'] for x in S]) if len(S) > 1 else 0:.2f}")
    macro("SuiteFalse", f"{sum(x['false_alarm_windows'] for x in S)}/{sum(x['calm_windows'] for x in S)}")
    macro("SuiteLatency", f"{st.mean(x['latency_ms_median'] for x in S):.0f}")
    if B:
        macro("BenignRuns", str(len(B)))
        macro("BenignFalse", f"{sum(x['false_alarm_windows'] for x in B)}/{sum(x['calm_windows'] for x in B)}")
        macro("BenignLatency", f"{st.mean(x['latency_ms_median'] for x in B):.0f}")
        macro("BenignPninetyfive", f"{st.mean(x['latency_ms_p95'] for x in B):.0f}")
    fb = eps.get("fb_drop", [])
    if fb:
        macro("FbDropTtm", f"{st.mean(e['time_to_mitigate_s'] for e in fb):.1f}")
    real = {p.parent.name.replace("scenario_", ""): J(p) for p in SIM.glob("real/scenario_*/summary.json")}
    for k, v in real.items():
        tag = {"trailer": "Trailer", "talking": "Talk"}.get(k, k)
        macro(f"Real{tag}Ttm", f"{v['mean_time_to_mitigate_s']:.2f}")
        macro(f"Real{tag}Mit", v["mitigated_episodes"].replace("/", "/"))
        macro(f"Real{tag}False", f"{v['false_alarm_windows']}/{v['calm_windows']}")

    runs = J(SIM / "policy_seeds" / "learning" / "runs.json")
    pol = {p: [r for r in runs if r["policy"] == p] for p in ("threshold", "bandit")}
    seeds = sorted({r["seed"] for r in runs})
    key = [("mean_time_to_mitigate_s", "Mitigation (s)", 2), ("mean_leakage_under_attack", "Leakage under attack", 3),
           ("mean_cost", "Encrypted share", 3), ("mean_cost_calm", "Encrypted share, calm", 3)]
    rows = []
    for k, lbl, nd in key:
        by = {p: {r["seed"]: r[k] for r in pol[p]} for p in pol}
        d = [by["bandit"][s] - by["threshold"][s] for s in seeds]
        wins = sum(x < 0 for x in d)
        rows.append(f"{lbl} & {ms(by['threshold'].values(), nd)} & {ms(by['bandit'].values(), nd)} & {wins}/{len(seeds)} \\\\")
    write("tab_policies.tex", rf"""\begin{{table}}[t]
\caption{{Threshold rule vs.\ $\varepsilon$-greedy bandit on the learning scenario, {len(seeds)} seeds each (mean\,$\pm$\,s.d.). The last column counts the seeds in which the bandit was better (lower) than the threshold rule with the same seed.}}
\label{{tab:policies}}
\centering\small\setlength{{\tabcolsep}}{{4pt}}
\begin{{tabular}}{{lccc}}
\toprule
Metric & Threshold & Bandit & Bandit better \\
\midrule
{chr(10).join(rows)}
\bottomrule
\end{{tabular}}
\end{{table}}
""")
    th, bd = pol["threshold"], pol["bandit"]
    macro("Seeds", str(len(seeds)))
    macro("PolCostT", f"{st.mean(r['mean_cost'] for r in th):.3f}")
    macro("PolCostB", f"{st.mean(r['mean_cost'] for r in bd):.3f}")
    macro("PolCostSave", f"{100 * (1 - st.mean(r['mean_cost'] for r in bd) / st.mean(r['mean_cost'] for r in th)):.0f}")
    macro("PolTtmT", f"{st.mean(r['mean_time_to_mitigate_s'] for r in th):.2f}")
    macro("PolTtmB", f"{st.mean(r['mean_time_to_mitigate_s'] for r in bd):.2f}")
    macro("PolLeakB", f"{st.mean(r['mean_leakage_under_attack'] for r in bd):.3f}")
    macro("PolFalse", f"{sum(r['false_alarm_windows'] for r in runs)}/{sum(r['calm_windows'] for r in runs)}")

    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(figsize=(3.4, 2.1))
    for p, c, mk, lbl, side in (("threshold", BLUE, "o", "threshold rule", 1), ("bandit", ORANGE, "^", "bandit", -1)):
        xs = [r["mean_time_to_mitigate_s"] for r in pol[p]]
        ys = [100 * r["mean_cost"] for r in pol[p]]
        ax.plot(xs, ys, mk, ms=6, color=c, mec="white", mew=1.0, ls="none", label=lbl, zorder=3)
        ax.annotate(lbl, (max(xs) if side > 0 else min(xs), st.mean(ys)), xytext=(8 * side, 0),
                    textcoords="offset points", ha="left" if side > 0 else "right", va="center", color=INK, fontsize=7)
    ax.set_xlabel("mean time to mitigate (s)")
    ax.set_ylabel("payload bits encrypted (%)")
    ax.grid(color=GRID, lw=0.6)
    ax.set_axisbelow(True)
    ax.set_xlim(0, 1.8)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.legend(frameon=False, fontsize=7, loc="upper right")
    fig.tight_layout()
    fig.savefig(FIG / "fig_policies.pdf")
    plt.close(fig)


# ---------------------------------------------------------------- compliance, software cost
def misc():
    t = (DATA / "future_work_results" / "format_compliance.md").read_text().splitlines()
    head = [c.strip() for c in t[0].strip("|").split("|")][1:]
    ok = all(c.strip() == "yes" for line in t[2:] if line.startswith("|") for c in line.strip("|").split("|")[1:])
    macro("Decoders", ", ".join(head).replace("ffmpeg (MJPEG clip)", "FFmpeg (MJPEG)"))
    macro("NumDecoders", str(len(head)))
    macro("AllDecode", "all" if ok else r"\TODO{not all}")
    full = J(SIM / "benchmark_rtl" / "benchmark.json")
    for size, tag in (("320x240", "QVGA"), ("640x480", "VGA")):
        bb = full[size]
        e4 = next(v for k, v in bb.items() if k.startswith("in-encoder E4"))["out_bytes"]
        e5 = next(v for k, v in bb.items() if k.startswith("in-encoder E5"))["out_bytes"]
        e2 = next(v for k, v in bb.items() if k.startswith("in-encoder E2"))["out_bytes"]
        plain = next(v for k, v in bb.items() if k.startswith("plain JPEG"))["out_bytes"]
        macro(f"OverheadEfive{tag}", f"{100 * (e5 / e4 - 1):.0f}")
        macro(f"OverheadEtwo{tag}", f"{100 * (e2 / plain - 1):.1f}")
    b = full["640x480"]
    pick = lambda pre: next(v for k, v in b.items() if k.startswith(pre))
    macro("PyPlainMs", f"{pick('plain JPEG')['ms']:.0f}")
    macro("PySelEtwoMs", f"{pick('software selective E2')['ms']:.0f}")
    macro("AesGcmMs", f"{pick('full-stream AES-128-GCM')['ms']:.2f}")
    bl = next((DATA / "future_work_results").glob("baselines_*.json"), None)
    if bl:
        sizes = J(bl).get("sizes", {})
        if isinstance(sizes, str):                       # older files stored the dict as its repr
            import ast
            sizes = ast.literal_eval(sizes)
        vga = sizes.get("640x480", {})
        jt = next((v for k, v in vga.items() if "libjpeg" in k), None)
        if jt:
            macro("TurboFps", f"{jt['fps']:.0f}")
            macro("TurboMs", f"{jt['ms_per_frame']:.2f}")
    src = DATA / "future_work_results" / "visual_security_grid.pdf"
    if src.exists():
        shutil.copy(src, FIG / "fig_visual_grid.pdf")


def main():
    TAB.mkdir(exist_ok=True)
    FIG.mkdir(exist_ok=True)
    hardware()
    leakage()
    protocol()
    misc()
    lines = ["% generated by paper/make_assets.py from paper/data -- do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(macros.items())]
    (TAB / "numbers.tex").write_text("\n".join(lines) + "\n")
    print(f"{len(macros)} numbers, tables in {TAB}, figures in {FIG}")


if __name__ == "__main__":
    main()
