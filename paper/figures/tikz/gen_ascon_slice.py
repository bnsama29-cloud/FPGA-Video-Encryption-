"""Generates circuit_ascon.tex: one bit slice of the Ascon round of rtl/ascon_round.v, gate for gate.

    python paper/figures/tikz/gen_ascon_slice.py

The netlist below is copied from rtl/ascon_round.v (substitution layer); the linear layer acts on
whole 64-bit words, so it is drawn as one box per word with its two rotation amounts.
"""
from pathlib import Path

ROWS = [4.0, 2.9, 1.8, 0.7, -0.4]          # y of rows 0..4 (x0 top)
# substitution layer of rtl/ascon_round.v, slice j:  t = (a0, x1, a2, x3, a4)
#   a0 = x0 ^ x4 ; a4 = x4 ^ x3 ; a2 = x2 ^ x1   (x2 already carries the round constant bit)
#   b_i = t_i ^ (~t_{i+1} & t_{i+2})
#   c1 = b1 ^ b0 ; c0 = b0 ^ b4 ; c3 = b3 ^ b2 ; c2 = ~b2 ; c4 = b4
T_NAMES = ["a_0", "x_1", "a_2", "x_3", "a_4"]
OUT = [("c_0", ("b_0", "b_4")), ("c_1", ("b_1", "b_0")), ("c_2", ("b_2",)), ("c_3", ("b_3", "b_2")), ("c_4", ())]
SIGMA = [(19, 28), (61, 39), (1, 6), (10, 17), (7, 41)]

L = []
w = L.append
TAPS = {}


def tap(rail, x, ref):
    """Coordinate on rail `rail` (at x) level with the anchor `ref`; returns its name."""
    n = f"tp{rail}{len(TAPS.setdefault(rail, []))}"
    TAPS[rail].append(n)
    w(f"\\coordinate ({n}) at ({x},0 |- {ref});")
    return n
w("% One bit slice j (of 64) of the Ascon round, generated by gen_ascon_slice.py from rtl/ascon_round.v.")
w("\\begin{tikzpicture}[x=1cm, y=1cm, font=\\tiny]")
w("\\ctikzset{logic ports=ieee, logic ports/scale=0.5}")
w("\\tikzset{w/.style={inkc, line width=0.45pt}, sig/.style={font=\\tiny, inner sep=1pt},"
  " dot/.style={circle, fill=inkc, inner sep=0.75pt}, box/.style={draw=inkc, fill=white, font=\\tiny, align=center, inner sep=1.5pt}}")
# inputs
for i, y in enumerate(ROWS):
    w(f"\\node[sig, anchor=east] (in{i}) at (0,{y}) {{$x_{i}[j]$}};")
# round constant on x2
w(f"\\node[xor port] (rc) at (1.0,{ROWS[2] - 0.12}) {{}};")
w(f"\\draw[w] (in2) -| ([xshift=-1.5mm]rc.in 1) -- (rc.in 1);")
w(f"\\node[sig, anchor=east] (rcin) at (0,{ROWS[2] - 0.55}) {{$\\mathit{{rc}}_j$}};")
w(f"\\draw[w] (rcin) -| ([xshift=-2.5mm]rc.in 2) -- (rc.in 2);")
w(f"\\node[sig, above=0pt of rc] {{$p_C$}};")
# first XOR layer: a0 = x0^x4 (row 0), a2 = x2'^x1 (row 2), a4 = x4^x3 (row 4); x1, x3 pass through
# input rails (vertical) for x0..x4 at x = 1.6 + 0.12 i
RX = {i: 1.55 + 0.13 * i for i in range(5)}
for i, y in enumerate(ROWS):
    src = "rc.out" if i == 2 else f"in{i}"
    t = tap(f"r{i}", RX[i], src)
    w(f"\\draw[w] ({src}) -- ({t});")
XA = 2.85
first = {0: (0, 4), 2: (2, 1), 4: (4, 3)}     # row: (rail for in1, rail for in2)
for row, (p, q) in first.items():
    y = ROWS[row]
    w(f"\\node[xor port] (fa{row}) at ({XA},{y}) {{}};")
    w(f"\\draw[w] ({tap(f'r{p}', RX[p], f'fa{row}.in 1')}) -- (fa{row}.in 1);")
    w(f"\\draw[w] ({tap(f'r{q}', RX[q], f'fa{row}.in 2')}) -- (fa{row}.in 2);")
for row in (1, 3):
    y = ROWS[row]
    w(f"\\coordinate (fa{row}) at ({XA + 0.33},{y});")
    w(f"\\draw[w] ({tap(f'r{row}', RX[row], f'fa{row}')}) -- (fa{row});")
# t rails (second channel)
TX = {i: 3.55 + 0.13 * i for i in range(5)}
for i, y in enumerate(ROWS):
    src = f"fa{i}.out" if i in first else f"fa{i}"
    t = tap(f"t{i}", TX[i], src)
    w(f"\\draw[w] ({src}) -- ({t});")
    w(f"\\node[sig, anchor=south] at ($({src})!0.5!({t})$) {{${T_NAMES[i]}$}};")
# chi: per row i: NOT(t_{i+1}) -> AND with t_{i+2} -> XOR with t_i
XN, XAND, XX = 4.65, 5.55, 6.55
for i, y in enumerate(ROWS):
    j1, j2 = (i + 1) % 5, (i + 2) % 5
    w(f"\\node[and port] (and{i}) at ({XAND},{y}) {{}};")
    w(f"\\node[not port] (not{i}) at ({XN},0 |- and{i}.in 1) {{}};")
    w(f"\\draw[w] ({tap(f't{j1}', TX[j1], f'not{i}.in')}) -- (not{i}.in);")
    w(f"\\draw[w] (not{i}.out) -- (and{i}.in 1);")
    w(f"\\draw[w] ({tap(f't{j2}', TX[j2], f'and{i}.in 2')}) -- (and{i}.in 2);")
    w(f"\\node[xor port] (bx{i}) at ({XX},{y - 0.2}) {{}};")
    w(f"\\draw[w] (and{i}.out) -| ([xshift=-1.5mm]bx{i}.in 1) -- (bx{i}.in 1);")
    w(f"\\coordinate (lo{i}) at (0,{y - 0.42});")
    w(f"\\draw[w] ({tap(f't{i}', TX[i], f'lo{i}')}) -- ([xshift=-2.5mm]bx{i}.in 2 |- lo{i}) |- (bx{i}.in 2);")
w(f"\\node[sig] at ({(XN + XX) / 2},{ROWS[0] + 0.5}) {{$\\chi$: $b_i = t_i \\oplus (\\neg t_{{i+1}} \\wedge t_{{i+2}})$}};")
# b rails (third channel)
BX = {i: 7.25 + 0.13 * i for i in range(5)}
for i, y in enumerate(ROWS):
    t = tap(f"b{i}", BX[i], f"bx{i}.out")
    w(f"\\draw[w] (bx{i}.out) -- ({t});")
    w(f"\\node[sig, anchor=south] at ($(bx{i}.out)!0.45!({t})$) {{$b_{i}$}};")
# output layer
XO = 8.55
for i, (name, ins) in enumerate(OUT):
    y = ROWS[i]
    bi = [int(s[-1]) for s in ins]
    if len(ins) == 2:
        w(f"\\node[xor port] (o{i}) at ({XO},{y}) {{}};")
        w(f"\\draw[w] ({tap(f'b{bi[0]}', BX[bi[0]], f'o{i}.in 1')}) -- (o{i}.in 1);")
        w(f"\\draw[w] ({tap(f'b{bi[1]}', BX[bi[1]], f'o{i}.in 2')}) -- (o{i}.in 2);")
        out = f"o{i}.out"
    elif len(ins) == 1:
        w(f"\\node[not port] (o{i}) at ({XO},{y}) {{}};")
        w(f"\\draw[w] ({tap(f'b{bi[0]}', BX[bi[0]], f'o{i}.in')}) -- (o{i}.in);")
        out = f"o{i}.out"
    else:
        w(f"\\coordinate (o{i}) at ({XO + 0.3},{y});")
        w(f"\\coordinate (c4y) at (0,{y});")
        w(f"\\draw[w] ({tap('b4', BX[4], 'c4y')}) -- (o{i});")
        out = f"o{i}"
    r1, r2 = SIGMA[i]
    w(f"\\node[box, minimum width=27mm, minimum height=5mm] (sg{i}) at (11.75,{y}) "
      f"{{$\\Sigma_{i}$: ${name} \\oplus ({name} \\ggg {r1}) \\oplus ({name} \\ggg {r2})$}};")
    w(f"\\draw[w] ({out}) -- node[sig, above]{{${name}[j]$}} (sg{i}.west);")
    w(f"\\draw[w, -{{Latex[length=1.2mm]}}] (sg{i}.east) -- ++(0.35,0) node[sig, right]{{$x'_{i}$}};")
w(f"\\node[sig, align=center] at (11.75,{ROWS[0] + 0.5}) {{$p_L$ (whole 64-bit words; $\\ggg$ = rotate right)}};")
w(f"\\node[sig] at ({XA},{ROWS[0] + 0.5}) {{$p_S$ input layer}};")
w(f"\\node[sig] at ({XO},{ROWS[0] + 0.5}) {{output layer}};")
for rail, names in TAPS.items():
    w("\\draw[w] " + " -- ".join(f"({n})" for n in names) + ";")
    for n in names:
        w(f"\\node[dot] at ({n}) {{}};")
w("\\end{tikzpicture}")
Path(__file__).with_name("circuit_ascon.tex").write_text("\n".join(L) + "\n")
print("wrote circuit_ascon.tex")
