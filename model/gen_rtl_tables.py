"""Generate rtl/include/*.vh from the golden model so ROMs can never drift.

Run:  python -m model.gen_rtl_tables      (make tables does this)
"""
import os

from .jpeg import DCT_C
from .tables import ZIGZAG, DC_CODES, AC_CODES

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "rtl", "include")
HDR = "// AUTO-GENERATED by model/gen_rtl_tables.py -- do not edit by hand.\n"


def _lit(width, v):
    return ("-%d'sd%d" % (width, -v)) if v < 0 else ("%d'sd%d" % (width, v))


def gen_dct():
    lines = [HDR, "// C[u][x] = round(2^13 * c(u)/2 * cos((2x+1)u*pi/16)), index = {u, x}",
             "function signed [14:0] dct_c;", "  input [5:0] ux;", "  begin",
             "    case (ux)"]
    for u in range(8):
        for x in range(8):
            lines.append("      6'd%d: dct_c = %s;" % (u * 8 + x, _lit(15, DCT_C[u][x])))
    lines += ["      default: dct_c = 15'sd0;", "    endcase", "  end", "endfunction", ""]
    return "\n".join(lines)


def gen_zigzag():
    lines = [HDR, "// natural (row-major) index of zig-zag position k",
             "function [5:0] zz_nat;", "  input [5:0] k;", "  begin", "    case (k)"]
    for k, n in enumerate(ZIGZAG):
        lines.append("      6'd%d: zz_nat = 6'd%d;" % (k, n))
    lines += ["      default: zz_nat = 6'd0;", "    endcase", "  end", "endfunction", ""]
    return "\n".join(lines)


def gen_huff():
    lines = [HDR, "// returns {len[4:0], code[15:0]}; tbl 0 = luminance, 1 = chrominance",
             "function [20:0] huff_dc;", "  input       tbl;", "  input [3:0] size;",
             "  begin", "    case ({tbl, size})"]
    for t in range(2):
        for s, (c, l) in sorted(DC_CODES[t].items()):
            lines.append("      5'h%02x: huff_dc = {5'd%d, 16'h%04x};" % ((t << 4) | s, l, c))
    lines += ["      default: huff_dc = 21'd0;", "    endcase", "  end", "endfunction", "",
              "function [20:0] huff_ac;", "  input       tbl;", "  input [7:0] rs;  // {run, size}",
              "  begin", "    case ({tbl, rs})"]
    for t in range(2):
        for rs, (c, l) in sorted(AC_CODES[t].items()):
            lines.append("      9'h%03x: huff_ac = {5'd%d, 16'h%04x};" % ((t << 8) | rs, l, c))
    lines += ["      default: huff_ac = 21'd0;", "    endcase", "  end", "endfunction", ""]
    return "\n".join(lines)


def gen_hls_coeffs():
    rows = ",\n".join("    {" + ", ".join("%6d" % DCT_C[u][x] for x in range(8)) + "}" for u in range(8))
    return ("// AUTO-GENERATED by model/gen_rtl_tables.py -- do not edit by hand.\n"
            "#pragma once\n#include <stdint.h>\n"
            "// C[u][x] = round(2^13 * c(u)/2 * cos((2x+1)u*pi/16)); same table as rtl/include/dct_coeffs.vh\n"
            "static const int16_t DCT_C[8][8] = {\n" + rows + "\n};\n")


def main():
    os.makedirs(OUT, exist_ok=True)
    for name, fn in (("dct_coeffs.vh", gen_dct), ("zigzag.vh", gen_zigzag),
                     ("huff_tables.vh", gen_huff)):
        with open(os.path.join(OUT, name), "w") as f:
            f.write(fn())
        print("wrote rtl/include/" + name)
    with open(os.path.join(HERE, "..", "hls", "dct_coeffs.h"), "w") as f:
        f.write(gen_hls_coeffs())
    print("wrote hls/dct_coeffs.h")


if __name__ == "__main__":
    main()
