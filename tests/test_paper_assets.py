"""The paper is built from data: every number used in main.tex must exist, and the committed tables must
match what paper/make_assets.py produces from paper/data/ (so nobody edits a result by hand)."""
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / "paper"


def test_every_macro_in_the_text_is_defined():
    defined = set(re.findall(r"\\newcommand\{\\(\w+)\}", (PAPER / "tables" / "numbers.tex").read_text()))
    text = (PAPER / "main.tex").read_text()
    used = set(re.findall(r"(?<!\\)\\([A-Z][A-Za-z]+)\b", text))   # our macros: capital first letter, not after "\\\\"
    latex = {"TODO", "IEEEauthorblockN", "IEEEauthorblockA", "IEEEoverridecommandlockouts", "IEEEkeywords",
             "Latex"}
    missing = sorted(used - defined - latex)
    assert not missing, f"used in main.tex but not generated by make_assets.py: {missing}"


def test_committed_tables_match_the_data(tmp_path):
    copy = tmp_path / "paper"
    shutil.copytree(PAPER, copy, ignore=shutil.ignore_patterns("main.pdf", "*.aux", "*.log", "*.bbl", "*.blg"))
    for f in (copy / "tables").glob("*.tex"):
        f.unlink()
    subprocess.run([sys.executable, str(copy / "make_assets.py")], check=True, capture_output=True)
    for f in sorted((PAPER / "tables").glob("*.tex")):
        got, exp = (copy / "tables" / f.name).read_text(), f.read_text()
        assert got == exp, f"{f.name} is out of date: run `python paper/make_assets.py` and commit"


def test_every_citation_is_in_the_bibliography():
    keys = set(re.findall(r"@\w+\{(\w+),", (PAPER / "refs.bib").read_text()))
    cited = {k.strip() for group in re.findall(r"\\cite\{([^}]*)\}", (PAPER / "main.tex").read_text())
             for k in group.split(",")}
    assert cited <= keys, f"cited but not in refs.bib: {sorted(cited - keys)}"
    assert keys <= cited, f"in refs.bib but never cited (remove or cite): {sorted(keys - cited)}"
