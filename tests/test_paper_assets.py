"""The papers are built from data: every number used in conference.tex and access.tex (with its section
files) must exist, and the committed tables must match what paper/make_assets.py produces from paper/data/
(so nobody edits a result by hand)."""
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / "paper"


def sources():
    """The text of both papers: conference.tex, access.tex + sections/access_*.tex, the shared preamble."""
    files = [PAPER / "conference.tex", PAPER / "access.tex", PAPER / "common" / "preamble.tex"]
    files += sorted((PAPER / "sections").glob("access_*.tex"))
    return {f.name: f.read_text() for f in files}


def strip_comments(t):
    return re.sub(r"(?<!\\)%.*", "", t)


def test_every_macro_in_the_text_is_defined():
    defined = set(re.findall(r"\\newcommand\{\\(\w+)\}", (PAPER / "tables" / "numbers.tex").read_text()))
    texts = {k: strip_comments(v) for k, v in sources().items()}   # comments do not count
    for t in texts.values():
        defined |= set(re.findall(r"\\newcommand\{\\(\w+)\}", t))   # text macros (preamble, notation)
        defined |= set(re.findall(r"\\newtheorem\{(\w+)\}", t))
    latex = {"TODO", "IEEEauthorblockN", "IEEEauthorblockA", "IEEEoverridecommandlockouts", "IEEEkeywords",
             "IEEEproof", "IEEEbiographynophoto", "Latex", "EOD", "ExplSyntaxOn", "ExplSyntaxOff",
             "Require", "State", "For", "EndFor", "If", "EndIf", "Repeat", "Until", "Return", "Comment",
             "Delta", "Bigl", "Bigr"}                                   # math: Greek, delimiters
    for name, t in texts.items():
        used = set(re.findall(r"(?<!\\)\\([A-Z][A-Za-z]+)\b", t))   # our macros: capital first letter
        missing = sorted(used - defined - latex)
        assert not missing, f"used in {name} but not generated by make_assets.py: {missing}"


def test_committed_tables_match_the_data(tmp_path):
    copy = tmp_path / "paper"
    shutil.copytree(PAPER, copy, ignore=shutil.ignore_patterns("conference.pdf", "access.pdf", "*.aux", "*.log", "*.bbl", "*.blg"))
    for f in (copy / "tables").glob("*.tex"):
        f.unlink()
    subprocess.run([sys.executable, str(copy / "make_assets.py")], check=True, capture_output=True)
    for f in sorted((PAPER / "tables").glob("*.tex")):
        got, exp = (copy / "tables" / f.name).read_text(), f.read_text()
        assert got == exp, f"{f.name} is out of date: run `python paper/make_assets.py` and commit"


def test_every_citation_is_in_the_bibliography():
    keys = set(re.findall(r"@\w+\{(\w+),", (PAPER / "refs.bib").read_text()))
    text = "".join(sources().values()) + "".join(f.read_text() for f in (PAPER / "tables").glob("tab_*.tex"))
    cited = {k.strip() for group in re.findall(r"\\cite\{([^}]*)\}", text) for k in group.split(",")}
    assert cited <= keys, f"cited but not in refs.bib: {sorted(cited - keys)}"
    assert keys <= cited, f"in refs.bib but never cited (remove or cite): {sorted(keys - cited)}"


def test_conference_version_cites_fewer_references():
    """The 6-page version keeps a short reference list; the IEEE Access version cites everything."""
    def cites(t):
        return {k.strip() for g in re.findall(r"\\cite\{([^}]*)\}", t) for k in g.split(",")}
    tables = "".join(f.read_text() for f in (PAPER / "tables").glob("tab_*.tex"))
    conf = cites(strip_comments((PAPER / "conference.tex").read_text()))
    access = cites("".join(strip_comments(v) for k, v in sources().items() if k != "conference.tex") + tables)
    assert conf <= access
    assert len(conf) < len(access)
